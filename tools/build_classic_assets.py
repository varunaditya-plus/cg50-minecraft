#!/usr/bin/env python3
"""Convert the original PNG pixels into RGB565 plus a separate alpha plane."""
from pathlib import Path
import json
import hashlib
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
TEXTURES = ROOT / 'assets-cg/classic/textures'
NAMES = [
    'grass', 'dirt', 'grass_dirt', 'stone', 'wood', 'rock', 'bedrock',
    'sand', 'gravel', 'tree_top', 'tree_side', 'lava', 'rock_gold',
    'rock_bronze', 'rock_coal', 'gold', 'sponge',
    *[f'color{i}' for i in range(16)],
    'leaves_opaque', 'glass', 'water', 'bush', 'red_flower',
    'yellow_flower', 'red_mushroom', 'brown_mushroom',
]
INVENTORY = [2, 9, 3, 4, 13, 14, 8, 6, 5, 16, 15, 11, 12, 23, 22, 21, *range(24, 40)]
DEFAULT_HOTBAR = [2, 3, 4, 9, 11, 12, 13, 14, 15]
BLOCK_NAMES = [
    'Air', 'Grass', 'Stone', 'Dirt', 'Wood', 'Red flower', 'Yellow flower',
    'Water', 'Bush', 'Cobblestone', 'Bedrock', 'Sand', 'Gravel', 'Log',
    'Leaves', 'Red mushroom', 'Brown mushroom', 'Lava', 'Gold ore',
    'Iron ore', 'Coal ore', 'Gold', 'Sponge', 'Glass', 'Red wool',
    'Orange wool', 'Yellow wool', 'Lime wool', 'Green wool', 'Aqua wool',
    'Cyan wool', 'Light blue wool', 'Periwinkle wool', 'Violet wool', 'Lavender wool',
    'Magenta wool', 'Rose wool', 'Dark grey wool', 'Light grey wool', 'White wool',
    'Empty sponge', 'Water surface',
]
# Indices are [top, bottom, side], as in upstream registerBlock material tuples.
MATERIALS = {
    1: ['grass', 'dirt', 'grass_dirt'], 2: ['stone'] * 3,
    3: ['dirt'] * 3, 4: ['wood'] * 3, 5: ['red_flower'] * 3,
    6: ['yellow_flower'] * 3, 7: ['water'] * 3, 8: ['bush'] * 3,
    9: ['rock'] * 3, 10: ['bedrock'] * 3, 11: ['sand'] * 3,
    12: ['gravel'] * 3, 13: ['tree_top', 'tree_top', 'tree_side'],
    14: ['leaves_opaque'] * 3, 15: ['red_mushroom'] * 3,
    16: ['brown_mushroom'] * 3, 17: ['lava'] * 3,
    18: ['rock_gold'] * 3, 19: ['rock_bronze'] * 3,
    20: ['rock_coal'] * 3, 21: ['gold'] * 3, 22: ['sponge'] * 3,
    23: ['glass'] * 3, 41: ['water'] * 3,
    **{24 + i: [f'color{i}'] * 3 for i in range(16)},
}

def planes(path):
    with Image.open(path) as image:
        rgba = image.convert('RGBA')
        raw = rgba.tobytes()
        pixels = [raw[i:i + 4] for i in range(0, len(raw), 4)]
        rgb565 = [((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3) for r, g, b, a in pixels]
        alpha = [a for r, g, b, a in pixels]
        # Colour and alpha stay independent, so an opaque original black pixel is visible.
        return rgba.width, rgba.height, rgb565, alpha

def initializer(values, hexadecimal=False, indent='    '):
    fmt = (lambda value: f'0x{value:04x}') if hexadecimal else str
    return ',\n'.join(indent + ', '.join(map(fmt, values[i:i + 16])) for i in range(0, len(values), 16))

def emit_array(ctype, name, values, static=True, hexadecimal=False):
    scope = 'static ' if static else ''
    return f'{scope}const {ctype} {name}[{len(values)}] = {{\n{initializer(values, hexadecimal)}\n}};\n'

header = '''// Generated by tools/build_classic_assets.py which converts Minecraft Classic PNG textures and interface images into RGB565 data with separate alpha planes. This was made by ai
#ifndef CLASSIC_ASSETS_H
#define CLASSIC_ASSETS_H
#include <stdint.h>
enum ClassicTexture {
'''
header += ''.join(f'    TEX_{name.upper()},\n' for name in NAMES)
header += '''    TEX_COUNT
};
#define CLASSIC_TEXTURE_EDGE 16
#define CLASSIC_INVENTORY_COUNT 32
#define CLASSIC_HOTBAR_COUNT 9
#define CLASSIC_BLOCK_COUNT 42

typedef struct {
    uint16_t width;
    uint16_t height;
    const uint16_t *pixels;
    const uint8_t *alpha;
} ClassicSprite;

extern const uint16_t classic_textures[TEX_COUNT][256];
extern const uint8_t classic_texture_alpha[TEX_COUNT][256];
// The three faces are top, bottom, and side. -1 means no rendered material.
extern const int8_t classic_block_texture[CLASSIC_BLOCK_COUNT][3];
extern const char * const classic_block_names[CLASSIC_BLOCK_COUNT];
extern const uint8_t classic_inventory_blocks[CLASSIC_INVENTORY_COUNT];
extern const uint8_t classic_default_hotbar[CLASSIC_HOTBAR_COUNT];
// Original previews are 32x32; the browser shows them at 16x16.
extern const ClassicSprite classic_previews[CLASSIC_INVENTORY_COUNT];
extern const ClassicSprite classic_hotbar_background;
extern const ClassicSprite classic_hotbar_selection;
extern const ClassicSprite classic_crosshair;
#endif
'''
body = '// Generated by tools/build_classic_assets.py which converts Minecraft Classic PNG textures and interface images into RGB565 data with separate alpha planes. This was made by ai\n#include "assets.h"\n\n'
textures = [planes(TEXTURES / f'{name}.png') for name in NAMES]
assert all(width == height == 16 for width, height, _, _ in textures)
for ctype, array_name, plane, hexadecimal in [('uint16_t', 'classic_textures', 2, True), ('uint8_t', 'classic_texture_alpha', 3, False)]:
    body += f'const {ctype} {array_name}[TEX_COUNT][256] = {{\n'
    for name, data in zip(NAMES, textures):
        body += f'    {{ // {name}.png\n{initializer(data[plane], hexadecimal, "        ")}\n    }},\n'
    body += '};\n\n'
body += 'const int8_t classic_block_texture[CLASSIC_BLOCK_COUNT][3] = {\n'
for block in range(42):
    faces = [NAMES.index(material) for material in MATERIALS[block]] if block in MATERIALS else [-1] * 3
    body += '    {' + ', '.join(map(str, faces)) + f'}}, // {block}: {BLOCK_NAMES[block]}\n'
body += '};\n\nconst char * const classic_block_names[CLASSIC_BLOCK_COUNT] = {\n'
body += ''.join('    ' + json.dumps(name) + ',\n' for name in BLOCK_NAMES)
body += '};\n\n'
body += emit_array('uint8_t', 'classic_inventory_blocks', INVENTORY, static=False) + '\n'
body += emit_array('uint8_t', 'classic_default_hotbar', DEFAULT_HOTBAR, static=False) + '\n'
preview_entries = []
for block in INVENTORY:
    width, height, pixels, alpha = planes(TEXTURES / 'previews' / f'{block}.png')
    assert width == height == 32
    name = f'preview_{block}'
    body += emit_array('uint16_t', f'{name}_pixels', pixels, hexadecimal=True)
    body += emit_array('uint8_t', f'{name}_alpha', alpha)
    preview_entries.append(f'    {{{width}, {height}, {name}_pixels, {name}_alpha}}')
body += '\nconst ClassicSprite classic_previews[CLASSIC_INVENTORY_COUNT] = {\n' + ',\n'.join(preview_entries) + '\n};\n\n'
for filename, identifier in [('hotbar_bg', 'classic_hotbar_background'), ('hotbar_selection', 'classic_hotbar_selection'), ('crosshair', 'classic_crosshair')]:
    width, height, pixels, alpha = planes(TEXTURES / f'{filename}.png')
    body += emit_array('uint16_t', f'{identifier}_pixels', pixels, hexadecimal=True)
    body += emit_array('uint8_t', f'{identifier}_alpha', alpha)
    body += f'const ClassicSprite {identifier} = {{{width}, {height}, {identifier}_pixels, {identifier}_alpha}};\n\n'
(ROOT / 'src/assets.h').write_text(header)
(ROOT / 'src/assets.c').write_text(body)
manifest = []
for path in sorted(TEXTURES.rglob('*.png')):
    relative = path.relative_to(TEXTURES).as_posix()
    with Image.open(path) as image:
        width, height = image.size
    manifest.append({
        'path': 'assets-cg/classic/textures/' + relative,
        'url': 'https://classic.minecraft.net/assets/textures/' + relative,
        'sha256': hashlib.sha256(path.read_bytes()).hexdigest(),
        'bytes': path.stat().st_size, 'width': width, 'height': height,
    })
(ROOT / 'third_party/classic/assets-manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
print(f'Converted {len(NAMES)} original textures and {len(INVENTORY)} previews; checked {len(manifest)} original PNG hashes.')
