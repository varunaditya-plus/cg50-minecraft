#!/usr/bin/env node
// Execute Minecraft Classic's original worker, then compress its output for ROM.
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const crypto = require('crypto');
const root = path.resolve(__dirname, '..');
const seedIndex = process.argv.indexOf('--seed');
const seed = seedIndex < 0 ? 12345 : Number(process.argv[seedIndex + 1]);
if (!Number.isSafeInteger(seed)) throw new Error('--seed must be a safe integer');
const size = 128, height = 64, edge = 8;
let receive, tiles;
const sourcePath = path.join(root, 'third_party/classic/RandomLevelWorker.js');
const source = fs.readFileSync(sourcePath, 'utf8');
const context = vm.createContext({
    console: { log() {} },
    self: {
        addEventListener(type, handler) { if (type === 'message') receive = handler; },
        postMessage(message) { if (message.tiles) tiles = message.tiles; },
    },
});
vm.runInContext(source, context, { filename: sourcePath });
receive({ data: { worldSize: size, seed } });
const original = Buffer.from(tiles);
if (original.length !== size * size * height) throw new Error('Unexpected world dimensions');
const hash = data => crypto.createHash('sha256').update(data).digest('hex');
const goldens = {
    1: 'ea76833d1baeb698683dbb6fb6a9ce485fcf58219751f9f56a0cdbdcc036fb4a',
    42: '07be432a523a6fadccfa6c921273f55035cf2394fd65d4b2e2de0d7b73e26cbf',
    12345: '2865b462809b9f6ceed34651e26be7c0c930d3efb5e31385f79d723b629edca1',
};
const worldHash = hash(original);
if (goldens[seed] && goldens[seed] !== worldHash) throw new Error('Original worker output changed');
const offsets = [0], runs = [], restored = Buffer.alloc(original.length);
for (let cy = 0; cy < height / edge; cy++) {
    for (let cz = 0; cz < size / edge; cz++) {
        for (let cx = 0; cx < size / edge; cx++) {
            let previous = -1, length = 0;
            for (let ly = 0; ly < edge; ly++) {
                for (let lz = 0; lz < edge; lz++) {
                    for (let lx = 0; lx < edge; lx++) {
                        const index = (((cy * edge + ly) * size + cz * edge + lz) * size + cx * edge + lx);
                        const block = original[index];
                        if (block > 63) throw new Error('RLE block ID exceeds six bits');
                        if (block === previous) length++;
                        else {
                            if (length) runs.push(((length - 1) << 6) | previous);
                            previous = block; length = 1;
                        }
                    }
                }
            }
            runs.push(((length - 1) << 6) | previous);
            offsets.push(runs.length);
            let local = 0;
            for (let word = offsets[offsets.length - 2]; word < runs.length; word++) {
                const block = runs[word] & 63, count = (runs[word] >>> 6) + 1;
                for (let j = 0; j < count; j++, local++) {
                    const lx = local & 7, lz = (local >>> 3) & 7, ly = local >>> 6;
                    restored[(((cy * 8 + ly) * size + cz * 8 + lz) * size + cx * 8 + lx)] = block;
                }
            }
            if (local !== 512) throw new Error('Chunk did not decode to 512 blocks');
        }
    }
}
if (!original.equals(restored)) throw new Error('Compression changed the original world');
// Exact lightDepths exclusion list from upstream entry.js initialization.
const transparent = new Set([0, 5, 6, 8, 14, 15, 16, 23, 40]);
const light = new Uint8Array(size * size);
for (let x = 0; x < size; x++) {
    for (let z = 0; z < size; z++) {
        let depth = 0;
        for (let y = 0; y < height; y++) {
            if (!transparent.has(original[(y * size + z) * size + x])) depth = y;
        }
        light[z * size + x] = depth;
    }
}
const emit = (type, name, values, width = 16) => {
    const rows = [];
    for (let i = 0; i < values.length; i += width) rows.push('    ' + Array.from(values.slice(i, i + width)).join(', '));
    return `const ${type} ${name}[${values.length}] = {\n${rows.join(',\n')}\n};\n`;
};
const header = `// Generated by tools/generate_classic_level.cjs; original worker output.
#ifndef CLASSIC_LEVEL_DATA_H
#define CLASSIC_LEVEL_DATA_H
#include <stdint.h>
#define CLASSIC_WORLD_SIZE 128
#define CLASSIC_WORLD_HEIGHT 64
#define CLASSIC_CHUNK_EDGE 8
#define CLASSIC_CHUNK_COUNT 2048
#define CLASSIC_CHUNK_RUN_COUNT ${runs.length}
extern const int32_t classic_seed;
extern const uint32_t classic_chunk_offsets[2049];
extern const uint16_t classic_chunk_runs[CLASSIC_CHUNK_RUN_COUNT];
// Indexed z * 128 + x, matching upstream lightDepths[x][z].
extern const uint8_t classic_light_depth[128 * 128];
#endif
`;
const body = `// Original worker world SHA256: ${worldHash}\n// Generated from seed ${seed}; 8x8x8 chunks, ((run - 1) << 6) | block.\n#include "level_data.h"\nconst int32_t classic_seed = ${seed};\n\n` +
    emit('uint32_t', 'classic_chunk_offsets', offsets) + '\n' +
    emit('uint16_t', 'classic_chunk_runs', runs) + '\n' +
    emit('uint8_t', 'classic_light_depth', light);
fs.writeFileSync(path.join(root, 'src/level_data.h'), header);
fs.writeFileSync(path.join(root, 'src/level_data.c'), body);
const manifest = {
    seed, size, height, worker_sha256: hash(source), world_sha256: worldHash,
    layout: '(y * 128 + z) * 128 + x', chunk_edge: edge,
    chunk_id: '(cy * 16 + cz) * 16 + cx', local_id: '(ly * 8 + lz) * 8 + lx',
    rle_word: '((run_length - 1) << 6) | block_id', runs: runs.length,
    rom_bytes: offsets.length * 4 + runs.length * 2 + light.length,
    decoded_chunk_bytes: 512, verified_exact_roundtrip: true,
};
fs.writeFileSync(path.join(root, 'third_party/classic/level-manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
console.log(`Seed ${seed}: ${worldHash}; ${runs.length} runs; ${manifest.rom_bytes} ROM bytes; exact roundtrip verified.`);
