// Bake the very same native NOA mesher used for edited calculator chunks.
// The level itself comes from the unchanged original JavaScript worker.
#include "mesh.h"
#include "world.h"
#include <stdio.h>
#include <stdlib.h>
#include <limits.h>

int main(void)
{
    uint32_t offsets[2049];
    FILE *out = fopen("src/mesh_data.c", "w");
    if (!out) return 1;
    fputs("// Generated by tools/generate_meshes.c; do not edit.\n"
          "#include \"mesh_data.h\"\n"
          "const ClassicQuad classic_mesh_quads[] = {\n", out);
    unsigned total = 0;
    world_init();
    for (int y = 0; y < 8; y++) for (int z = 0; z < 16; z++)
        for (int x = 0; x < 16; x++) {
            unsigned count;
            ClassicQuad *q = mesh_build_chunk(x, y, z, &count);
            if (count == UINT_MAX) return 1;
            offsets[(y * 16 + z) * 16 + x] = total;
            total += count;
            for (unsigned i = 0; i < count; i++)
                fprintf(out, "{%u,%u,%u,%u,%u,%u,%u,%u},\n", q[i].x,
                    q[i].y, q[i].z, q[i].width, q[i].height, q[i].face,
                    q[i].block, q[i].dark);
            free(q);
        }
    offsets[2048] = total;
    fputs("};\nconst uint32_t classic_mesh_offsets[2049] = {\n", out);
    for (int i = 0; i < 2049; i++) fprintf(out, "%u,%c", offsets[i],
        i % 12 == 11 ? '\n' : ' ');
    fputs("\n};\n", out);
    fclose(out);
    printf("Baked %u original terrain quads (%u bytes).\n", total, total * 8);
    return 0;
}
